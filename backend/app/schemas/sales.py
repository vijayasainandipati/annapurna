import uuid
from datetime import datetime
from decimal import Decimal
from typing import Optional, List
from pydantic import BaseModel, ConfigDict, Field

class OrderItemInput(BaseModel):
    product_id: uuid.UUID
    quantity: int = Field(..., gt=0, description="Quantity of packets ordered")

class OrderCreate(BaseModel):
    customer_id: uuid.UUID
    items: List[OrderItemInput] = Field(..., min_length=1, description="Order items")
    idempotency_key: Optional[str] = Field(None, description="UUID key generated by client for offline deduplication")
    notes: Optional[str] = None

class OrderStatusUpdate(BaseModel):
    status: str = Field(..., description="Target status: APPROVED, REJECTED, CANCELLED")
    rejection_reason: Optional[str] = None

class OrderItemResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    product_id: uuid.UUID
    product_name: str
    product_sku: str
    quantity: int
    unit_price: Decimal
    taxable_amount: Decimal
    tax_amount: Decimal
    line_total: Decimal

class OrderResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    order_number: str
    customer_id: uuid.UUID
    customer_name: str
    customer_state: str
    customer_gstin: Optional[str] = None
    salesman_id: uuid.UUID
    salesman_name: str
    status: str
    idempotency_key: Optional[str] = None
    total_taxable_amount: Decimal
    total_tax_amount: Decimal
    total_order_amount: Decimal
    rejection_reason: Optional[str] = None
    notes: Optional[str] = None
    created_at: datetime
    updated_at: datetime
    items: List[OrderItemResponse] = []

class OrderStockPrecheckItem(BaseModel):
    product_id: uuid.UUID
    product_name: str
    product_sku: str
    requested_quantity: int
    available_stock: Decimal
    projected_stock: Decimal
    has_shortage: bool
    shortage_quantity: int

class OrderStockPrecheckResponse(BaseModel):
    order_id: uuid.UUID
    order_number: str
    items: List[OrderStockPrecheckItem]
    can_fulfill_completely: bool
    total_requested: int
    total_available: Decimal

class InvoiceItemDetail(BaseModel):
    product_name: str
    sku: str
    hsn_code: str
    quantity: int
    unit_price: Decimal
    taxable_amount: Decimal
    gst_rate: Decimal
    tax_amount: Decimal
    total_amount: Decimal

class InvoiceResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    invoice_number: str
    order_id: uuid.UUID
    customer_id: uuid.UUID
    customer_name: str
    customer_state: str
    customer_gstin: Optional[str] = None
    taxable_amount: Decimal
    cgst_amount: Decimal
    sgst_amount: Decimal
    igst_amount: Decimal
    total_amount: Decimal
    paid_amount: Decimal
    outstanding_amount: Decimal
    status: str
    is_interstate: bool
    created_at: datetime
    items: List[InvoiceItemDetail] = []

class DispatchCreate(BaseModel):
    order_id: uuid.UUID
    invoice_id: uuid.UUID
    partial_quantity: Optional[int] = Field(None, gt=0, description="Optional approved partial dispatch quantity")
    notes: Optional[str] = None

class DispatchResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    dispatch_number: str
    order_id: uuid.UUID
    invoice_id: uuid.UUID
    dispatched_quantity: int
    remaining_finished_stock: Decimal
    dispatched_at: datetime
    dispatched_by_name: str
